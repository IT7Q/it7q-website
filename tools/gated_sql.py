#!/usr/bin/env python3
"""Turn gated/*.json into the SQL that loads web.nda_content (PLAN.md §4.9, DEPLOY.md step 8).

    python3 tools/gated_sql.py --validate      # shape and coverage only (tests use this)
    python3 tools/gated_sql.py > gated.sql     # refuses unless every file says "reviewed": true

The SQL replaces the whole table in one transaction, as it7q_web_owner. 'notes' fields are
for Chris and are dropped here, so they never reach the database or the site.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
GATED = ROOT / "gated"
MAX_SECTIONS, MAX_ITEMS, MAX_TEXT = 30, 50, 4000  # the same limits as src/assets/js/nda.js


class GatedError(Exception):
    pass


def check_sections(where, sections):
    if not isinstance(sections, list) or not sections or len(sections) > MAX_SECTIONS:
        raise GatedError("%s: sections must be a list of 1-%d" % (where, MAX_SECTIONS))
    for s in sections:
        if not isinstance(s, dict) or set(s) - {"heading", "items", "paragraphs"} or not isinstance(s.get("heading"), str):
            raise GatedError("%s: each section is {heading, items?, paragraphs?}" % where)
        if not (s.get("items") or s.get("paragraphs")):
            raise GatedError("%s: section %r is empty" % (where, s["heading"]))
        for key in ("items", "paragraphs"):
            values = s.get(key, [])
            if not isinstance(values, list) or len(values) > MAX_ITEMS:
                raise GatedError("%s: %s must be a list of up to %d" % (where, key, MAX_ITEMS))
            for v in values:
                if not isinstance(v, str) or not v.strip() or len(v) > MAX_TEXT:
                    raise GatedError("%s: %s entries must be text up to %d characters" % (where, key, MAX_TEXT))
    return sections


def body(where, entry):
    if not isinstance(entry, dict) or set(entry) - {"summary", "sections", "notes"}:
        raise GatedError("%s: an entry is {summary, sections, notes?}" % where)
    if not isinstance(entry.get("summary"), str) or not entry["summary"].strip():
        raise GatedError("%s: missing summary" % where)
    return {"summary": entry["summary"], "sections": check_sections(where, entry.get("sections"))}


def load(require_reviewed=True):
    """[(division, project_id, version, body)] for every gated project, plus the investor page."""
    projects = build.load_json("projects.json")
    divisions = [d["slug"] for d in build.load_json("divisions.json")]
    gated_ids = {p["id"]: p["division"] for p in projects if p.get("gated") is not False}
    rows, seen, unreviewed = [], set(), []
    for path in sorted(GATED.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        div = data.get("division")
        where = "gated/" + path.name
        if path.stem != div or (div not in divisions and div != "investors"):
            raise GatedError("%s: division must match the file name and be a real division" % where)
        if data.get("reviewed") is not True:
            unreviewed.append(where)
        version = data.get("version", 1)
        if div == "investors":
            rows.append((div, "_page", version, {"sections": check_sections(where, data.get("sections"))}))
            continue
        entries = dict(data.get("projects", {}))
        for pid, pdiv in gated_ids.items():  # FABRICUS catalogue items share one entry
            if "catalogue" in data and pdiv == div and pid.startswith("P-FAB-0") and pid not in entries:
                entries[pid] = data["catalogue"]
        for pid, entry in sorted(entries.items()):
            if gated_ids.get(pid) != div:
                raise GatedError("%s: %s isn't a gated %s project in projects.json" % (where, pid, div))
            rows.append((div, pid, version, body("%s %s" % (where, pid), entry)))
            seen.add(pid)
    missing = sorted(set(gated_ids) - seen)
    if missing:
        raise GatedError("no gated detail for: " + ", ".join(missing))
    if not any(r[0] == "investors" for r in rows):
        raise GatedError("gated/investors.json is missing")
    if require_reviewed and unreviewed:
        raise GatedError("not reviewed yet (set \"reviewed\": true after reading): " + ", ".join(unreviewed))
    return rows


def literal(text):
    return "'" + text.replace("'", "''") + "'"


def to_sql(rows):
    values = ",\n".join("  (%s, %s, %d, %s::jsonb)" % (literal(d), literal(p), v,
                                                     literal(json.dumps(b, ensure_ascii=False, sort_keys=True)))
                        for d, p, v, b in rows)
    return ("-- Generated by tools/gated_sql.py from gated/*.json. Run as the superuser in it7q_web.\n"
            "\\set ON_ERROR_STOP on\nBEGIN;\nSET LOCAL ROLE it7q_web_owner;\nDELETE FROM web.nda_content;\n"
            "INSERT INTO web.nda_content (division, project_id, version, body) VALUES\n%s;\n"
            "SELECT division, count(*) FROM web.nda_content GROUP BY division ORDER BY division;\nCOMMIT;\n" % values)


def main(argv):
    try:
        rows = load(require_reviewed="--validate" not in argv)
    except GatedError as e:
        print("gated: %s" % e, file=sys.stderr)
        return 1
    if "--validate" in argv:
        print("gated detail OK: %d rows" % len(rows), file=sys.stderr)
        return 0
    sys.stdout.write(to_sql(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
